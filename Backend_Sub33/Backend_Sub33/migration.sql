CREATE TABLE cat_hospitales (
    hospital_id integer GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(150) NOT NULL,
    direccion character varying(200),
    ciudad character varying(100),
    codigo_postal character varying(20),
    CONSTRAINT "PK_cat_hospitales" PRIMARY KEY (hospital_id)
);

CREATE TABLE cat_rangos (
    rango_id integer GENERATED BY DEFAULT AS IDENTITY,
    rango character varying(50) NOT NULL,
    minimo integer NOT NULL,
    maximo integer NOT NULL,
    CONSTRAINT "PK_cat_rangos" PRIMARY KEY (rango_id)
);

CREATE TABLE cat_tipos_emergencia (
    tipo_emergencia_id integer GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(100) NOT NULL,
    descripcion character varying(200),
    CONSTRAINT "PK_cat_tipos_emergencia" PRIMARY KEY (tipo_emergencia_id)
);

CREATE TABLE configuracion_listas_maestras (
    lista_id integer GENERATED BY DEFAULT AS IDENTITY,
    categoria character varying(100) NOT NULL,
    opcion character varying(100) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_configuracion_listas_maestras" PRIMARY KEY (lista_id)
);

CREATE TABLE permisos (
    permiso_id uuid NOT NULL DEFAULT (gen_random_uuid()),
    codigo character varying(100) NOT NULL,
    descripcion character varying(255),
    CONSTRAINT "PK_permisos" PRIMARY KEY (permiso_id)
);

CREATE TABLE roles (
    rol_id character varying(50) NOT NULL,
    nombre character varying(100) NOT NULL,
    descripcion character varying(255),
    CONSTRAINT "PK_roles" PRIMARY KEY (rol_id)
);

CREATE TABLE personal (
    personal_id uuid NOT NULL DEFAULT (gen_random_uuid()),
    primer_nombre character varying(100) NOT NULL,
    segundo_nombre character varying(100),
    primer_apellido character varying(100) NOT NULL,
    segundo_apellido character varying(100),
    dpi character varying(20) NOT NULL,
    fecha_nacimiento date,
    rango_id integer,
    fecha_ingreso date NOT NULL,
    telefono character varying(20) NOT NULL,
    estado boolean NOT NULL DEFAULT TRUE,
    contacto_emergencia_nombre character varying(150),
    contacto_emergencia_telefono character varying(20),
    CONSTRAINT "PK_personal" PRIMARY KEY (personal_id),
    CONSTRAINT fk_personal_rango FOREIGN KEY (rango_id) REFERENCES cat_rangos (rango_id) ON DELETE SET NULL
);

CREATE TABLE rol_permisos (
    rol_id character varying(50) NOT NULL,
    permiso_id uuid NOT NULL,
    CONSTRAINT "PK_rol_permisos" PRIMARY KEY (rol_id, permiso_id),
    CONSTRAINT fk_rol_permiso_permiso FOREIGN KEY (permiso_id) REFERENCES permisos (permiso_id) ON DELETE CASCADE,
    CONSTRAINT fk_rol_permiso_rol FOREIGN KEY (rol_id) REFERENCES roles (rol_id) ON DELETE CASCADE
);

CREATE TABLE usuarios (
    usuario_id uuid NOT NULL DEFAULT (gen_random_uuid()),
    personal_id uuid,
    username character varying(100) NOT NULL,
    password_hash character varying(255) NOT NULL,
    estado boolean NOT NULL DEFAULT TRUE,
    ultimo_login timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    updated_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_usuarios" PRIMARY KEY (usuario_id),
    CONSTRAINT fk_usuario_personal FOREIGN KEY (personal_id) REFERENCES personal (personal_id) ON DELETE SET NULL
);

CREATE TABLE usuario_roles (
    usuario_id uuid NOT NULL,
    rol_id character varying(50) NOT NULL,
    CONSTRAINT "PK_usuario_roles" PRIMARY KEY (usuario_id, rol_id),
    CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (rol_id) REFERENCES roles (rol_id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (usuario_id) ON DELETE CASCADE
);

