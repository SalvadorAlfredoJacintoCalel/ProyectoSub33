-- Migración única: tabla de auditoría de acciones por usuario.
-- Se registra cada petición mutante (POST/PUT/PATCH/DELETE) autenticada.
-- Solo crea la estructura (sin registros). Ejecutar una sola vez en Neon.

CREATE TABLE IF NOT EXISTS public.bitacora_acciones (
    accion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id uuid,
    usuario_nombre character varying(150),
    metodo character varying(10) NOT NULL,
    ruta character varying(300) NOT NULL,
    modulo character varying(100) NOT NULL,
    accion character varying(120) NOT NULL,
    fecha_hora timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bitacora_acciones_usuario FOREIGN KEY (usuario_id)
        REFERENCES public.usuarios(usuario_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_bitacora_acciones_usuario
    ON public.bitacora_acciones (usuario_id);

CREATE INDEX IF NOT EXISTS idx_bitacora_acciones_fecha
    ON public.bitacora_acciones (fecha_hora DESC);
